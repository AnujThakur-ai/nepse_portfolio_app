  static final Map<String, CompanyProfile> _updatedCompanies = {};

  /// Returns combined list of benchmark + user added custom companies + live variations
  static List<CompanyProfile> get allCompanies {
    final Map<String, CompanyProfile> map = {};
    for (final c in _benchmarkCompanies) {
      map[c.symbol] = c;
    }
    for (final c in _customCompanies) {
      map[c.symbol] = c;
    }
    for (final entry in _updatedCompanies.entries) {
      map[entry.key] = entry.value;
    }
    return map.values.toList();
  }

  static List<CompanyProfile> get initialCompanies => allCompanies;

  /// Find company by stock symbol
  static CompanyProfile? findBySymbol(String symbol) {
    final query = symbol.trim().toUpperCase();
    if (_updatedCompanies.containsKey(query)) {
      return _updatedCompanies[query];
    }
    try {
      return allCompanies.firstWhere((c) => c.symbol == query);
    } catch (_) {
      return null;
    }
  }

  /// Adds a custom company to the system
  static void addCustomCompany(CompanyProfile company) {
    _customCompanies.removeWhere((c) => c.symbol == company.symbol);
    _customCompanies.add(company);
    _updatedCompanies.remove(company.symbol);
  }

  /// Updates live price variation for a company
  static void updatePriceVariation(String symbol, double newPrice) {
    final old = findBySymbol(symbol);
    if (old != null) {
      final change = newPrice - old.previousClose;
      final pChange = old.previousClose > 0
          ? (change / old.previousClose) * 100
          : 0.0;
      final updatedRecent = [...old.recentPrices, newPrice];

      final updated = CompanyProfile(
        symbol: old.symbol,
        companyName: old.companyName,
        sector: old.sector,
        ltp: newPrice,
        openPrice: old.openPrice,
        highPrice: newPrice > old.highPrice ? newPrice : old.highPrice,
        lowPrice: newPrice < old.lowPrice ? newPrice : old.lowPrice,
        previousClose: old.previousClose,
        priceChange: change,
        percentageChange: pChange,
        volume: old.volume + 1500,
        peRatio: old.peRatio,
        pbRatio: old.pbRatio,
        eps: old.eps,
        bookValue: old.bookValue,
        fiftyTwoWeekHigh: newPrice > old.fiftyTwoWeekHigh
            ? newPrice
            : old.fiftyTwoWeekHigh,
        fiftyTwoWeekLow: newPrice < old.fiftyTwoWeekLow
            ? newPrice
            : old.fiftyTwoWeekLow,
        recentPrices: updatedRecent,
        marketCap: old.marketCap,
        description: old.description,
      );

      _updatedCompanies[old.symbol] = updated;
    }
  }

  /// Direct Google Finance and Search Trends URL generator
  static String getGoogleFinanceUrl(String symbol) {
    return 'https://www.google.com/finance/quote/$symbol:NPL';
  }

  static String getGoogleSearchTrendsUrl(String symbol) {
    final comp = findBySymbol(symbol);
    final query = comp != null
        ? '${comp.symbol} ${comp.companyName} NEPSE'
        : '$symbol share price NEPSE';
    return 'https://www.google.com/search?q=${Uri.encodeComponent(query)}';
  }

  /// Validates NEPSE Price tick size: must be multiple of Rs 0.10
  static bool isValidPriceTick(double price) {
    final rounded = (price * 10).round() / 10;
    return (price - rounded).abs() < 0.001;
  }

  /// Validates circuit limit (+-10%)
  static String? validateCircuitBounds(CompanyProfile company, double price) {
    if (price > company.upperCircuitLimit) {
      return 'Price exceeds +10% Upper Circuit Limit of Rs ${company.upperCircuitLimit.toStringAsFixed(1)}';
    }
    if (price < company.lowerCircuitLimit) {
      return 'Price drops below -10% Lower Circuit Limit of Rs ${company.lowerCircuitLimit.toStringAsFixed(1)}';
    }
    return null;
  }

  /// Search companies by symbol, company name, or sector
  static List<CompanyProfile> searchCompanies(String query) {
    if (query.isEmpty) return allCompanies;
    final q = query.toLowerCase();
    return allCompanies
        .where(
          (c) =>
              c.symbol.toLowerCase().contains(q) ||
              c.companyName.toLowerCase().contains(q) ||
              c.sector.toLowerCase().contains(q),
        )
        .toList();
  }
